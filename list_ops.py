# 1. Створення
def create_examples(n):
    """Три способи створити список: перелік, [0] * n, comprehension."""
    listed = [90, 75, 58, 88, 95]
    zeros = [0] * n
    squares = [i * i for i in range(n)]
    return listed, zeros, squares


